#!/usr/bin/env python3
"""Regenerate defs.js from ../src/catalog.py (brands, categories, part types, WhatsApp number)."""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "..", "src"))
import catalog as c
import estimates as est
wa = re.search(r'^WA\s*=\s*"(\d+)"', open(os.path.join(here, "..", "src", "build.py")).read(), re.M).group(1)
d = {
    "wa": wa,
    "brands": [{"id": i, "name": n} for i, n in c.BRANDS],
    "cats": sorted([{"id": i, "name": n, "line": l} for i, n, l, _ in c.CATS], key=lambda x: x["name"].lower()),
    "parts": [{"id": p[0], "cat": p[1], "name": p[2], "alias": p[3], "side": p[4], "unit": p[5], "need": p[6]} for p in sorted(c.PARTS, key=lambda p: p[2].lower())],
    # rough market estimates, only used to pre-fill the "Add prices" tab (staff confirm before saving)
    "est": {"base": est.BASE, "looks": sorted(est.LOOKS),
            "car": {x["key"]: est.car_factors(x) for x in json.load(open(os.path.join(here, "..", "src", "db", "cars.json")))}},
}
open(os.path.join(here, "defs.js"), "w").write("/* generated by gen_defs.py from ../src/catalog.py */\nwindow.AT_DEFS=" + json.dumps(d, separators=(",", ":")) + ";\n")
print("defs.js:", len(d["parts"]), "parts,", len(d["cats"]), "cats")
